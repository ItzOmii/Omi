#!/usr/bin/env python3
"""Turn the kernel's own symbol table into a C array.

A fault can name the function it died in only if the names are in the image, and
they are not: the ELF symbol table is metadata the bootloader never loads. So the
build links the kernel once, reads the text symbols out of that ELF, and links
again with them compiled in as data.

That second link is safe because of where the table lands: the linker script puts
.rodata after .text and before .data, and this table only adds bytes to .rodata,
so every text address from the first link is still correct in the second. Only
text symbols are kept - a frame pointer walk lands in code by definition, and
keeping data symbols would triple the table for names nobody will see.
"""
import subprocess
import sys


def text_symbols(elf):
    out = subprocess.run(['nm', '-n', '--defined-only', elf],
                         capture_output=True, text=True, check=True).stdout
    syms = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        addr, kind, name = parts
        if kind not in 'tTwW':
            continue
        if not name or name.startswith('.') or name.startswith('$'):
            continue
        try:
            syms.append((int(addr, 16), name))
        except ValueError:
            continue
    syms.sort()
    # Two names at one address (aliases) would break the binary search's
    # "nearest address below" answer at that exact address; keep the first.
    out_syms, last = [], None
    for a, n in syms:
        if a == last:
            continue
        out_syms.append((a, n))
        last = a
    return out_syms


def chunk(blob, size=64):
    return [blob[i:i + size] for i in range(0, len(blob), size)]


def emit(syms, path):
    blob = bytearray()
    entries = []
    for addr, name in syms:
        entries.append((addr, len(blob)))
        blob += name.encode('ascii', 'replace') + b'\0'

    def lit(b):
        return ''.join('\\x%02x' % c for c in b)

    lines = [
        '/* Generated by tools/gen_symtab.py from the kernel ELF. Do not edit. */',
        '#include <stdint.h>',
        '',
        'typedef struct { uint64_t addr; uint32_t name; } bt_sym_t;',
        '',
    ]
    if not syms:
        lines += ['const char bt_names[] = "";',
                  'const bt_sym_t bt_syms[] = {{0, 0}};',
                  'const unsigned bt_sym_count = 0;']
    else:
        lines.append('const char bt_names[] =')
        parts = chunk(blob)
        for i, part in enumerate(parts):
            tail = ';' if i == len(parts) - 1 else ''
            lines.append('  "%s"%s' % (lit(part), tail))
        lines.append('')
        lines.append('const bt_sym_t bt_syms[] = {')
        for addr, off in entries:
            lines.append('  {0x%016xULL, %u},' % (addr, off))
        lines.append('};')
        lines.append('const unsigned bt_sym_count = %u;' % len(entries))
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    if len(sys.argv) != 3:
        print('usage: gen_symtab.py <kernel.elf> <out.c>', file=sys.stderr)
        return 2
    syms = text_symbols(sys.argv[1])
    if not syms:
        print('%s: no text symbols - is it stripped?' % sys.argv[1], file=sys.stderr)
        return 1
    emit(syms, sys.argv[2])
    print('gen_symtab: %d text symbols' % len(syms))
    return 0


if __name__ == '__main__':
    sys.exit(main())