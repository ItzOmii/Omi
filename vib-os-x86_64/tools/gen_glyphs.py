#!/usr/bin/env python3
"""Generate userland/glyphs.h from the kernel's bitmap font.

The kernel keeps its 8x16 table in kernel/gui/font.c as font_data[256][16]. A
ring-3 rasteriser needs the same shapes, and a second hand-copied table would
drift the day someone edits a glyph. So the table is extracted here, on every
build of the header, and the extraction fails loudly if it does not find what it
expects.
"""
import re
import sys

SRC = "kernel/gui/font.c"
OUT = "userland/glyphs.h"
FIRST, LAST = 32, 126


def strip_comments(text):
    """The table is commented glyph by glyph, and one of those comments is
    `// 0x7B - {` - a brace inside a comment. Counting braces in raw source
    merges glyph 0x7B with 0x7C and silently shifts every glyph after it, which
    is exactly the sort of wrong that looks like a font bug."""
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def extract(path):
    s = strip_comments(open(path).read())
    m = re.search(r"font_data\s*\[\s*256\s*\]\s*\[\s*16\s*\]\s*=\s*\{", s)
    if not m:
        sys.exit("gen_glyphs: font_data[256][16] not found in %s" % path)
    i = m.end()
    depth = 1
    glyphs, cur = [], None
    while i < len(s) and depth > 0:
        c = s[i]
        if c == "{":
            depth += 1
            if depth == 2:
                cur = []
        elif c == "}":
            if depth == 2:
                glyphs.append(cur)
                cur = None
            depth -= 1
        elif cur is not None and c == "0" and s[i:i + 2].lower() == "0x":
            j = i + 2
            while j < len(s) and s[j] in "0123456789abcdefABCDEF":
                j += 1
            cur.append(int(s[i:j], 16))
            i = j
            continue
        i += 1
    # The table is declared [256][16] but the source initialises fewer: C fills
    # the tail with zero rows, which are blank glyphs. Pad rather than refuse,
    # but refuse a count that cannot be a prefix of 256.
    if len(glyphs) > 256:
        sys.exit("gen_glyphs: parsed %d glyphs, more than the 256 declared"
                 % len(glyphs))
    if len(glyphs) < 256:
        print("gen_glyphs: %d of 256 glyphs initialised, %d padded blank"
              % (len(glyphs), 256 - len(glyphs)), file=sys.stderr)
        glyphs = glyphs + [[0] * 16 for _ in range(256 - len(glyphs))]
    for n, g in enumerate(glyphs):
        if len(g) != 16:
            sys.exit("gen_glyphs: glyph %d has %d rows, expected 16" % (n, len(g)))
        for v in g:
            if not 0 <= v <= 0xFF:
                sys.exit("gen_glyphs: glyph %d has row value 0x%X" % (n, v))
    return glyphs


def main():
    g = extract(SRC)
    sel = g[FIRST:LAST + 1]
    empty = [i for i, gl in enumerate(sel) if not any(gl)]
    if empty:
        print("gen_glyphs: %d blank glyphs (expected: space only)" % len(empty),
              file=sys.stderr)
    if not any(sel[0x41 - FIRST]):
        sys.exit("gen_glyphs: 'A' is blank - wrong offset or a corrupt table")
    if sel[0x7B - FIRST][2] != 0x0E:
        sys.exit("gen_glyphs: '{' is wrong - the brace glyph shifted")

    with open(OUT, "w") as f:
        f.write("/* Generated by tools/gen_glyphs.py from kernel/gui/font.c.\n"
                " * Do not edit: edit the kernel table, or this header goes stale.\n"
                " * 8x16 rows, high bit is the leftmost pixel. */\n")
        f.write("#ifndef GLYPHS_H\n#define GLYPHS_H\n\n")
        f.write("#define GLYPH_W %d\n#define GLYPH_H 16\n" % 8)
        f.write("#define GLYPH_FIRST %d\n#define GLYPH_LAST %d\n" % (FIRST, LAST))
        f.write("static const unsigned char glyphs[%d][16] = {\n" % len(sel))
        for n, gl in enumerate(sel):
            ch = FIRST + n
            label = chr(ch) if 32 < ch < 127 else "sp"
            if ch == 39 or ch == 92:
                label = "sq" if ch == 39 else "bs"
            f.write("  {%s}, /* %3d %s */\n" %
                    (", ".join("0x%02X" % v for v in gl), ch, label))
        f.write("};\n\n#endif\n")
    print("gen_glyphs: wrote %s, %d glyphs (%d..%d), %d non-blank"
          % (OUT, len(sel), FIRST, LAST, len(sel) - len(empty)))


if __name__ == "__main__":
    main()