#!/usr/bin/env python3
"""Bake Remix Icon (Iconify `ri`) glyphs into the MeepOS kernel.

The kernel has no SVG renderer, so each glyph is rasterised here to a square
8-bit coverage mask (0 = empty, 255 = solid ink) and emitted as a C array.
The compositor blends those masks, which keeps the icons anti-aliased at any
ui_scale without shipping a vector engine.

    ./tools/gen_ri_icons.py            # rewrite kernel/gui/icons_ri.{c,h}
"""
import json
import os
import subprocess
import sys
import urllib.request

SRC = 48                     # mask is SRC x SRC; drawn scaled at runtime
ICONS_JSON = "/tmp/ri/icons.json"
CDN = "https://cdn.jsdelivr.net/npm/@iconify-json/ri@1/icons.json"

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# enum name -> (remix icon name, comment)
SET = [
    ("ICON_CALC",       "calculator-line",   "calculator app"),
    ("ICON_NOTES",      "file-text-line",    "notes app"),
    ("ICON_MEDIA",      "music-2-line",      "media player app"),
    ("ICON_BROWSER",    "global-line",       "meepnet app"),
    ("ICON_CLOCK",      "time-line",         "clock widget"),
    ("ICON_WEATHER",    "sun-cloudy-line",   "weather widget"),
    ("ICON_STICKY",     "sticky-note-line",  "sticky widget"),
    ("ICON_APPEARANCE", "palette-line",      "appearance toggle"),
    ("ICON_APPS",       "apps-line",         "start menu / apps"),
    ("ICON_CLOSE",      "close-line",        "window close"),
    ("ICON_MIN",        "subtract-line",     "window minimise"),
    ("ICON_MAX",        "fullscreen-line",   "window maximise"),
]


def load_set():
    if os.path.exists(ICONS_JSON):
        with open(ICONS_JSON) as fh:
            return json.load(fh)
    print("downloading %s" % CDN)
    req = urllib.request.Request(CDN, headers={"User-Agent": "curl/8"})
    raw = urllib.request.urlopen(req, timeout=60).read()
    os.makedirs(os.path.dirname(ICONS_JSON), exist_ok=True)
    with open(ICONS_JSON, "wb") as fh:
        fh.write(raw)
    return json.loads(raw)


def render(icons, body_name, out_png):
    entry = icons["icons"][body_name]
    w = entry.get("width", icons.get("width", 24))
    h = entry.get("height", icons.get("height", 24))
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
        'viewBox="0 0 %s %s"><g fill="#000">%s</g></svg>'
        % (SRC * 8, SRC * 8, w, h, entry["body"].replace('fill="currentColor"', ""))
    )
    svg_path = out_png + ".svg"
    with open(svg_path, "w") as fh:
        fh.write(svg)
    subprocess.run(
        ["rsvg-convert", "-w", str(SRC * 8), "-h", str(SRC * 8),
         "-o", out_png, svg_path],
        check=True,
    )
    return out_png


def to_mask(png_path):
    from PIL import Image
    im = Image.open(png_path).convert("RGBA").resize((SRC, SRC), Image.LANCZOS)
    return [255 - px[3] if px[3] else 0 for px in im.getdata()] \
        if False else [px[3] for px in im.getdata()]


def main():
    icons = load_set()
    os.makedirs("/tmp/ri/bake", exist_ok=True)
    rows = {}
    for enum, name, _ in SET:
        png = render(icons, name, "/tmp/ri/bake/%s.png" % name)
        rows[enum] = to_mask(png)

    cf = os.path.join(ROOT, "kernel", "gui", "icons_ri.c")
    with open(cf, "w") as fh:
        fh.write("/* Generated by tools/gen_ri_icons.py - do not edit.\n"
                 "   Glyphs: Remix Icon (ri) via Iconify, Apache-2.0. */\n")
        fh.write('#include "icons_ri.h"\n\n')
        fh.write("const unsigned char ri_icon_mask[ICON_COUNT][ICON_SRC * ICON_SRC] = {\n")
        for enum, name, _ in SET:
            fh.write("  [%s] = {          /* ri/%s */\n" % (enum, name))
            vals = rows[enum]
            for i in range(0, len(vals), 32):
                fh.write("    " + ",".join("%d" % v for v in vals[i:i + 32]) + ",\n")
            fh.write("  },\n")
        fh.write("};\n")

    hf = os.path.join(ROOT, "kernel", "gui", "icons_ri.h")
    with open(hf, "w") as fh:
        fh.write("/* Generated by tools/gen_ri_icons.py - do not edit. */\n"
                 "#ifndef MEEP_ICONS_RI_H\n#define MEEP_ICONS_RI_H\n\n")
        fh.write("#define ICON_SRC %d\n\n" % SRC)
        fh.write("enum {\n")
        for i, (enum, name, comment) in enumerate(SET):
            fh.write("  %s = %d,%s/* ri/%s - %s */\n"
                     % (enum, i, " " * max(1, 20 - len(enum)), name, comment))
        fh.write("  ICON_COUNT\n};\n\n")
        fh.write("extern const unsigned char ri_icon_mask[ICON_COUNT][ICON_SRC * ICON_SRC];\n\n")
        fh.write("#endif\n")

    print("wrote %s (%d icons, %dpx masks)" % (cf, len(SET), SRC))


if __name__ == "__main__":
    sys.exit(main())